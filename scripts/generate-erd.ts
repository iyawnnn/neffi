import { mkdir, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import { drizzle } from "drizzle-orm/pglite";
import { migrate } from "drizzle-orm/pglite/migrator";

type Column = {
  table: string;
  name: string;
  type: string;
  not_null: boolean;
  default: string | null;
  identity: string;
  pk: boolean;
  fk: boolean;
  uk: boolean;
};
type Constraint = {
  table: string;
  name: string;
  kind: string;
  definition: string;
  parent: string | null;
  required: boolean;
  identifying: boolean;
};
type CatalogEntry = { table: string; name: string; definition: string };

const cell = (value: string) => value.replaceAll("|", "\\|").replaceAll("\n", "<br>");

export async function generateErd(): Promise<string> {
  const client = new PGlite();
  try {
    await migrate(drizzle({ client }), { migrationsFolder: "drizzle" });
    const { rows: columns } = await client.query<Column>(`
      SELECT c.relname AS "table", a.attname AS name, format_type(a.atttypid, a.atttypmod) AS type,
        a.attnotnull AS not_null, pg_get_expr(d.adbin, d.adrelid) AS "default", a.attidentity AS identity,
        EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid = c.oid AND k.contype = 'p' AND a.attnum = ANY(k.conkey)) AS pk,
        EXISTS (SELECT 1 FROM pg_constraint k WHERE k.conrelid = c.oid AND k.contype = 'f' AND a.attnum = ANY(k.conkey)) AS fk,
        EXISTS (SELECT 1 FROM pg_index i WHERE i.indrelid = c.oid AND i.indisunique AND NOT i.indisprimary
          AND i.indpred IS NULL AND a.attnum = ANY(i.indkey)) AS uk
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
      JOIN pg_attribute a ON a.attrelid = c.oid
      LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
      WHERE n.nspname = 'public' AND c.relkind = 'r' AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY c.relname, a.attnum
    `);
    const { rows: constraints } = await client.query<Constraint>(`
      SELECT c.relname AS "table", k.conname AS name, k.contype AS kind,
        pg_get_constraintdef(k.oid, true) AS definition, p.relname AS parent,
        NOT EXISTS (SELECT 1 FROM pg_attribute a WHERE a.attrelid = c.oid
          AND a.attnum = ANY(k.conkey) AND NOT a.attnotnull) AS required,
        EXISTS (SELECT 1 FROM pg_constraint pk WHERE pk.conrelid = c.oid
          AND pk.contype = 'p' AND k.conkey <@ pk.conkey) AS identifying
      FROM pg_constraint k JOIN pg_class c ON c.oid = k.conrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      LEFT JOIN pg_class p ON p.oid = k.confrelid
      WHERE n.nspname = 'public' AND c.relkind = 'r' AND k.contype IN ('p', 'f', 'u', 'c')
      ORDER BY c.relname, k.conname
    `);
    const { rows: indexes } = await client.query<CatalogEntry>(`
      SELECT c.relname AS "table", i.relname AS name, pg_get_indexdef(i.oid) AS definition
      FROM pg_index x JOIN pg_class c ON c.oid = x.indrelid
      JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND c.relkind = 'r' ORDER BY c.relname, i.relname
    `);
    const { rows: triggers } = await client.query<CatalogEntry>(`
      SELECT c.relname AS "table", t.tgname AS name, pg_get_triggerdef(t.oid, true) AS definition
      FROM pg_trigger t JOIN pg_class c ON c.oid = t.tgrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = 'public' AND NOT t.tgisinternal ORDER BY c.relname, t.tgname
    `);
    const { rows: functions } = await client.query<{ name: string; definition: string }>(`
      SELECT p.proname AS name, pg_get_functiondef(p.oid) AS definition
      FROM pg_proc p JOIN pg_namespace n ON n.oid = p.pronamespace
      WHERE n.nspname = 'public' AND p.prokind = 'f' ORDER BY p.proname
    `);
    const { rows: enums } = await client.query<{ name: string; values: string[] }>(`
      SELECT t.typname AS name, array_agg(e.enumlabel ORDER BY e.enumsortorder) AS values
      FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace JOIN pg_enum e ON e.enumtypid = t.oid
      WHERE n.nspname = 'public' GROUP BY t.typname ORDER BY t.typname
    `);

    const tables = [...new Set(columns.map((column) => column.table))];
    const lines = [
      "# Database ERD", "",
      "Generated by `pnpm db:erd` from all committed migrations applied to a fresh, in-process PGlite database. Do not edit by hand.", "",
      "This is the migrated local schema; live Neon verification is a separate gated step. The Drizzle migration journal is excluded from the domain catalog.", "",
      `${tables.length} tables, ${enums.length} enums, ${constraints.length} constraints, ${indexes.length} indexes, ${triggers.length} triggers, ${functions.length} trigger functions.`, "",
      "## Relationships", "",
      "Nullable foreign keys allow zero or one parent. Solid lines identify join-table primary keys; dotted lines are other foreign keys. PK/FK/UK mark column membership; composite and partial uniqueness is defined in the catalog below. SQL types with spaces use underscores in the diagram.", "",
      "```mermaid", "erDiagram",
    ];
    for (const table of tables) {
      lines.push(`  ${table} {`);
      for (const column of columns.filter((column) => column.table === table)) {
        const keys = [column.pk && "PK", column.fk && "FK", column.uk && "UK"].filter(Boolean).join(",");
        lines.push(`    ${column.type.replaceAll(" ", "_")} ${column.name}${keys ? ` ${keys}` : ""} "${column.not_null ? "required" : "nullable"}"`);
      }
      lines.push("  }");
    }
    for (const fk of constraints.filter((constraint) => constraint.kind === "f")) {
      lines.push(`  ${fk.parent} ${fk.required ? "||" : "|o"}${fk.identifying ? "--" : ".."}o{ ${fk.table} : "${fk.name}"`);
    }
    lines.push("```", "", "## Enums", "", "| Enum | Values |", "|---|---|");
    for (const entry of enums) lines.push(`| \`${entry.name}\` | ${entry.values.map((value) => `\`${value}\``).join(", ")} |`);
    lines.push("", "## Table catalog", "", "Foreign keys without an explicit delete action use PostgreSQL's `NO ACTION` default. All current foreign keys are non-deferrable, so these prevent orphaned history at statement end. Only auth identities/sessions and profile links use `CASCADE`.");
    const kinds: Record<string, string> = { p: "Primary key", f: "Foreign key", u: "Unique", c: "Check" };
    for (const table of tables) {
      lines.push("", `### ${table}`, "", "| Column | SQL type | Nullable | Default / identity |", "|---|---|---|---|");
      for (const column of columns.filter((column) => column.table === table)) {
        const defaultValue = column.identity === "a" ? "GENERATED ALWAYS AS IDENTITY" : column.default ?? "—";
        lines.push(`| \`${column.name}\` | \`${column.type}\` | ${column.not_null ? "no" : "yes"} | ${defaultValue === "—" ? defaultValue : `\`${cell(defaultValue)}\``} |`);
      }
      lines.push("", "| Constraint | Kind | Definition |", "|---|---|---|");
      for (const constraint of constraints.filter((constraint) => constraint.table === table)) {
        lines.push(`| \`${constraint.name}\` | ${kinds[constraint.kind]} | \`${cell(constraint.definition)}\` |`);
      }
      lines.push("", "| Index | Definition |", "|---|---|");
      for (const index of indexes.filter((index) => index.table === table)) {
        lines.push(`| \`${index.name}\` | \`${cell(index.definition)}\` |`);
      }
      const tableTriggers = triggers.filter((trigger) => trigger.table === table);
      if (tableTriggers.length) {
        lines.push("", "| Trigger | Definition |", "|---|---|");
        for (const trigger of tableTriggers) lines.push(`| \`${trigger.name}\` | \`${cell(trigger.definition)}\` |`);
      }
    }
    lines.push("", "## Trigger functions", "", "Row triggers preserve lifecycle and recorded history. A deliberate development seed uses a guarded, explicit-table `TRUNCATE ... RESTRICT`, which bypasses row triggers.");
    for (const fn of functions) lines.push("", `### ${fn.name}`, "", "```sql", fn.definition.trim(), "```");
    return `${lines.join("\n")}\n`;
  } finally {
    await client.close();
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  generateErd()
    .then(async (erd) => {
      await mkdir("docs/database", { recursive: true });
      await writeFile("docs/database/erd.md", erd);
      console.log("Generated docs/database/erd.md from local migrations (PGlite).");
    })
    .catch((error: Error) => {
      console.error(`db:erd failed: ${error.message}`);
      process.exitCode = 1;
    });
}
